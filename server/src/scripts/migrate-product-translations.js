function translateVietnameseToLanguage(text, lang) {
  if (!text) return "";
  let result = text;
  
  const map = translationMaps[lang];
  if (!map) return text;
  
  // Apply phrase replacements first
  for (const [regex, replacement] of map.phrases) {
    result = result.replace(regex, replacement);
  }
  
  // Apply word replacements with Unicode-safe boundaries
  for (const [word, replacement] of map.words) {
    const regex = new RegExp(`(^|[^a-zA-Z0-9_À-ỹ])${word}($|[^a-zA-Z0-9_À-ỹ])`, 'gi');
    result = result.replace(regex, `$1${replacement}$2`);
  }
  
  return result;
}

async function main() {
  await connectDB();

  console.log("Fetching all products from DB...");
  const products = await Product.find({}).lean();
  console.log(`Found ${products.length} products to translate.`);

  let successCount = 0;

  for (const product of products) {
    // 1. vi (original content)
    await ProductTranslation.findOneAndUpdate(
      { product_id: product._id, language_code: "vi" },
      {
        name: product.name,
        short_description: product.short_description || "",
        description: product.description || "",
      },
      { upsert: true }
    );

    // 2. en, fr, zh translations
    for (const lang of ["en", "fr", "zh"]) {
      const translatedName = translateVietnameseToLanguage(product.name, lang);
      const translatedShortDesc = translateVietnameseToLanguage(product.short_description, lang);
      const translatedDesc = translateVietnameseToLanguage(product.description, lang);

      await ProductTranslation.findOneAndUpdate(
        { product_id: product._id, language_code: lang },
        {
          name: translatedName,
          short_description: translatedShortDesc,
          description: translatedDesc,
        },
        { upsert: true }
      );
    }

    successCount++;
    if (successCount % 10 === 0 || successCount === products.length) {
      console.log(`Processed translations for ${successCount}/${products.length} products.`);
    }
  }

  console.log("Migration completed successfully!");
  process.exit(0);
}

if (require.main === module) {
  main().catch((error) => {
    console.error("Migration failed:", error);
    process.exit(1);
  });
}

